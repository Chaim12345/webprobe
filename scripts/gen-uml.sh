#!/usr/bin/env bash
# gen-uml.sh — regenerate the UML diagrams under docs/uml/ from the source.
#
# Class diagrams come from auto-uml (cargo install auto-uml), which reads the
# Rust source with tree-sitter and writes Mermaid. One diagram per code area:
# a single diagram of the whole workspace is too large to read or render.
# The crate diagram comes from `cargo metadata`.
#
# Usage: scripts/gen-uml.sh
set -euo pipefail

ROOT=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
OUT="$ROOT/docs/uml"
command -v auto-uml >/dev/null || { echo "auto-uml not found: cargo install auto-uml" >&2; exit 1; }
mkdir -p "$OUT"

# name : source directory : title
AREAS=(
  "support:app/support/src:Support crate (shared types, TLS, codecs, utilities)"
  "report:app/report/src:Report crate (HTML and XML scan reports)"
  "core-net:app/core/src/net:Engine: proxy, interception, sending, shared state"
  "core-scan:app/core/src/scan:Engine: scanner run, issues, crawl and audit"
  "core-scan-checks:app/core/src/scan_checks:Engine: scan checks"
  "core-bcheck:app/core/src/bcheck:Engine: BCheck parser and runner"
  "desktop-ui:app/src/ui:Desktop app: UI views"
)

for area in "${AREAS[@]}"; do
  IFS=: read -r name dir title <<<"$area"
  tmp=$(mktemp)
  auto-uml -l rust -s "$ROOT/$dir" -d "$tmp" >/dev/null
  {
    echo "# $title"
    echo
    echo "Generated by \`scripts/gen-uml.sh\` from \`$dir\`. Do not edit by hand."
    echo
    echo '```mermaid'
    cat "$tmp"
    echo '```'
  } >"$OUT/$name.md"
  rm -f "$tmp"
  echo "wrote docs/uml/$name.md"
done

python3 - "$ROOT" "$OUT/crates.md" <<'PY'
import json, subprocess, sys
root, out = sys.argv[1], sys.argv[2]
meta = json.loads(subprocess.check_output(
    ["cargo", "metadata", "--format-version", "1", "--no-deps", "--locked"], cwd=f"{root}/app"))
names = {p["name"] for p in meta["packages"]}
lines = ["# Workspace crates", "",
         "Generated by `scripts/gen-uml.sh` from `cargo metadata`. Do not edit by hand.", "",
         "An arrow points from a crate to a workspace crate it depends on.", "",
         "```mermaid", "flowchart TD"]
ident = lambda n: n.replace("-", "_")
for p in sorted(meta["packages"], key=lambda p: p["name"]):
    kinds = sorted({k for t in p["targets"] for k in t["kind"] if k in ("lib", "bin")})
    lines.append(f'    {ident(p["name"])}["{p["name"]}<br/>{", ".join(kinds)}"]')
for p in sorted(meta["packages"], key=lambda p: p["name"]):
    for d in sorted({d["name"] for d in p["dependencies"] if d["name"] in names and d.get("kind") is None}):
        lines.append(f'    {ident(p["name"])} --> {ident(d)}')
lines += ["```", ""]
open(out, "w").write("\n".join(lines))
print("wrote docs/uml/crates.md")
PY
